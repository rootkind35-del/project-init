#!/usr/bin/env python3
"""
write_memory.py — Converts scan_project.py JSON output into PROJECT_MEMORY.md.

Usage (called by the AI after scanning):
    python scan_project.py <root> | python write_memory.py <root>

Or standalone with a JSON file:
    python write_memory.py <root> < scan_output.json
"""

import sys
import json
from pathlib import Path
from datetime import datetime, timezone


def fmt_bytes(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024:
            return f"{n:.0f} {unit}"
        n /= 1024
    return f"{n:.1f} TB"


def build_markdown(data: dict) -> str:
    name = data.get("project_name", "Unknown Project")
    root = data.get("workspace_root", "")
    scanned = data.get("scanned_at", datetime.now(timezone.utc).isoformat())
    total_files = data.get("total_files", 0)
    total_lines = data.get("total_lines", 0)
    total_bytes = data.get("total_bytes", 0)
    stack = data.get("stack", [])
    frameworks = data.get("frameworks", [])
    key_files = data.get("key_files", [])
    dir_map = data.get("dir_map", {})
    conventions = data.get("conventions", [])
    dev_commands = data.get("dev_commands", {})
    license_name = data.get("license", "Unknown")
    git = data.get("git", {})
    lang_breakdown = data.get("language_breakdown", [])

    lines = []

    # Header
    lines.append(f"# PROJECT_MEMORY — {name}")
    lines.append("")
    lines.append("> Auto-generated by `project-init` skill. Re-run `/init` to update.")
    lines.append("")

    # Stats bar
    lines.append("## Project Identity")
    lines.append("")
    lines.append(f"| Field | Value |")
    lines.append(f"|-------|-------|")
    lines.append(f"| **Name** | `{name}` |")
    lines.append(f"| **Root** | `{root}` |")
    lines.append(f"| **License** | {license_name} |")
    if git.get("remote"):
        lines.append(f"| **Remote** | {git['remote']} |")
    if git.get("branch"):
        lines.append(f"| **Branch** | `{git['branch']}` |")
    if git.get("last_commit"):
        c = git["last_commit"]
        lines.append(f"| **Last Commit** | `{c['hash']}` by {c['author']} — {c['message'][:60]} |")
    lines.append(f"| **Files** | {total_files:,} |")
    lines.append(f"| **Lines of Code** | {total_lines:,} |")
    lines.append(f"| **Total Size** | {fmt_bytes(total_bytes)} |")
    lines.append(f"| **Last Scanned** | {scanned} |")
    lines.append("")

    # Tech stack
    lines.append("## Tech Stack")
    lines.append("")
    if stack:
        lines.append("**Languages / Runtimes:** " + ", ".join(f"`{s}`" for s in stack))
    if frameworks:
        lines.append("")
        lines.append("**Frameworks & Libraries:** " + ", ".join(f"`{f}`" for f in frameworks))
    if lang_breakdown:
        lines.append("")
        lines.append("**Top languages by lines:**")
        lines.append("")
        for item in lang_breakdown:
            lines.append(f"- `{item['ext']}` — {item['lines']:,} lines")
    lines.append("")

    # Directory map
    if dir_map:
        lines.append("## Directory Map")
        lines.append("")
        lines.append("```")
        lines.append(f"{name}/")
        for d, purpose in sorted(dir_map.items()):
            lines.append(f"  {d}/  — {purpose}")
        lines.append("```")
        lines.append("")

    # Key files
    if key_files:
        lines.append("## Key Files")
        lines.append("")
        for kf in key_files:
            lines.append(f"- `{kf['path']}` — {kf['purpose']}")
        lines.append("")

    # Dev commands
    if dev_commands:
        lines.append("## Dev Commands")
        lines.append("")
        lines.append("| Command | Description |")
        lines.append("|---------|-------------|")
        for cmd, script in dev_commands.items():
            lines.append(f"| `{cmd}` | `{script}` |")
        lines.append("")

    # Conventions
    if conventions:
        lines.append("## Conventions")
        lines.append("")
        for c in conventions:
            lines.append(f"- {c}")
        lines.append("")

    # Footer note for AI
    lines.append("---")
    lines.append("")
    lines.append(
        "_This file is injected automatically before every AI invocation via the "
        "`project-memory-injector` PreInvocation hook. "
        "The AI must read and internalize this context before responding._"
    )
    lines.append("")

    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: write_memory.py <workspace_root> < scan_output.json", file=sys.stderr)
        sys.exit(1)

    root = Path(sys.argv[1])

    try:
        data = json.loads(sys.stdin.read())
    except (json.JSONDecodeError, ValueError) as e:
        print(f"Error parsing JSON: {e}", file=sys.stderr)
        sys.exit(1)

    if "error" in data:
        print(f"Scanner error: {data['error']}", file=sys.stderr)
        sys.exit(1)

    md = build_markdown(data)
    output_path = root / "PROJECT_MEMORY.md"
    output_path.write_text(md, encoding="utf-8")
    print(f"Written: {output_path}", file=sys.stderr)
    print(md)


if __name__ == "__main__":
    main()
